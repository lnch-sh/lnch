// Package config reads and writes lnch.toml.
package config

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/pelletier/go-toml/v2"

	"lnch.sh/internal/plan"
)

type file struct {
	Name     string `toml:"name"`
	HTTPS    https  `toml:"https"`
	Share    share  `toml:"share"`
	Services []svc  `toml:"services"`
}

type https struct {
	Enabled *bool `toml:"enabled"`
}

type share struct {
	Service string `toml:"service"`
	Relay   string `toml:"relay"`
}

type svc struct {
	Name         string            `toml:"name"`
	Command      string            `toml:"command"`
	Cwd          string            `toml:"cwd"`
	Env          map[string]string `toml:"env"`
	Port         int               `toml:"port"`
	Health       string            `toml:"health"`
	DependsOn    []string          `toml:"depends_on"`
	Primary      bool              `toml:"primary"`
	Public       bool              `toml:"public"`
	Protocol     string            `toml:"protocol"`
	Restart      string            `toml:"restart"`
	ReadyTimeout string            `toml:"ready_timeout"`
}

// LoadRoot reads lnch.toml or .lnch.toml from root.
// It returns os.ErrNotExist when neither file is present.
func LoadRoot(root string) (*plan.Plan, error) {
	path, ok := Find(root)
	if !ok {
		return nil, os.ErrNotExist
	}
	return Load(path)
}

// Find returns the config path when one exists.
func Find(root string) (string, bool) {
	for _, name := range []string{"lnch.toml", ".lnch.toml"} {
		path := filepath.Join(root, name)
		if st, err := os.Stat(path); err == nil && !st.IsDir() {
			return path, true
		}
	}
	return "", false
}

// Load parses a config file into a plan. Directories are absolute.
func Load(path string) (*plan.Plan, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var f file
	if err := toml.Unmarshal(b, &f); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	root := filepath.Dir(path)
	root, err = filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	p := &plan.Plan{
		Name:   strings.TrimSpace(f.Name),
		Root:   root,
		Source: "lnch.toml",
		HTTPS:  true,
		Share: plan.Share{
			Service: f.Share.Service,
			Relay:   f.Share.Relay,
		},
	}
	if f.HTTPS.Enabled != nil {
		p.HTTPS = *f.HTTPS.Enabled
	}
	if p.Name == "" {
		p.Name = filepath.Base(root)
	}
	for _, s := range f.Services {
		dir := root
		if cwd := strings.TrimSpace(s.Cwd); cwd != "" && cwd != "." {
			if filepath.IsAbs(cwd) {
				dir = cwd
			} else {
				dir = filepath.Join(root, filepath.FromSlash(cwd))
			}
		}
		protocol := s.Protocol
		if protocol == "" {
			if strings.HasPrefix(s.Health, "tcp://") {
				protocol = "tcp"
			} else {
				protocol = "http"
			}
		}
		var timeout time.Duration
		if s.ReadyTimeout != "" {
			timeout, err = time.ParseDuration(s.ReadyTimeout)
			if err != nil {
				return nil, fmt.Errorf("%s: service %s ready_timeout: %w", path, s.Name, err)
			}
		}
		p.Services = append(p.Services, plan.Service{
			Name:         s.Name,
			Command:      s.Command,
			Dir:          dir,
			Env:          s.Env,
			Port:         s.Port,
			Health:       s.Health,
			DependsOn:    s.DependsOn,
			Primary:      s.Primary || (f.Share.Service != "" && s.Name == f.Share.Service),
			Public:       s.Public,
			Protocol:     protocol,
			Restart:      s.Restart,
			ReadyTimeout: timeout,
			Source:       "lnch.toml",
		})
	}
	if err := plan.Validate(p); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return p, nil
}

// Format renders a plan as lnch.toml. The result is stable enough to diff.
func Format(p *plan.Plan) string {
	var b strings.Builder
	b.WriteString("# Generated by lnch init. Edit commands, ports, and depends_on.\n")
	b.WriteString("# https://lnch.sh\n\n")
	fmt.Fprintf(&b, "name = %q\n\n", p.Name)
	if !p.HTTPS {
		b.WriteString("[https]\nenabled = false\n\n")
	}
	if p.Share.Service != "" || p.Share.Relay != "" {
		b.WriteString("[share]\n")
		if p.Share.Service != "" {
			fmt.Fprintf(&b, "service = %q\n", p.Share.Service)
		}
		if p.Share.Relay != "" {
			fmt.Fprintf(&b, "relay = %q\n", p.Share.Relay)
		}
		b.WriteString("\n")
	}
	for _, s := range p.Services {
		b.WriteString("[[services]]\n")
		fmt.Fprintf(&b, "name = %q\n", s.Name)
		fmt.Fprintf(&b, "command = %q\n", s.Command)
		cwd := relCwd(p.Root, s.Dir)
		if cwd != "." {
			fmt.Fprintf(&b, "cwd = %q\n", cwd)
		}
		if s.Protocol != "" && s.Protocol != "http" {
			fmt.Fprintf(&b, "protocol = %q\n", s.Protocol)
		}
		if s.Port > 0 {
			fmt.Fprintf(&b, "port = %d\n", s.Port)
		}
		if s.Health != "" {
			fmt.Fprintf(&b, "health = %q\n", s.Health)
		}
		if len(s.DependsOn) > 0 {
			b.WriteString("depends_on = [")
			for i, d := range s.DependsOn {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", d)
			}
			b.WriteString("]\n")
		}
		if s.Primary {
			b.WriteString("primary = true\n")
		}
		if s.Public {
			b.WriteString("public = true\n")
		}
		if s.Restart != "" && s.Restart != "no" {
			fmt.Fprintf(&b, "restart = %q\n", s.Restart)
		}
		keys := make([]string, 0, len(s.Env))
		for k := range s.Env {
			keys = append(keys, k)
		}
		sortStrings(keys)
		for _, k := range keys {
			if envKeyOK(k) {
				fmt.Fprintf(&b, "env.%s = %q\n", k, s.Env[k])
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}

func relCwd(root, dir string) string {
	if dir == "" || root == "" {
		return "."
	}
	rel, err := filepath.Rel(root, dir)
	if err != nil || rel == "." {
		return "."
	}
	return filepath.ToSlash(rel)
}

func envKeyOK(k string) bool {
	if k == "" {
		return false
	}
	for i, r := range k {
		if i == 0 && !((r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') || r == '_') {
			return false
		}
		if !((r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_') {
			return false
		}
	}
	return true
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// Exists reports whether a config file is already in root.
func Exists(root string) bool {
	_, ok := Find(root)
	return ok
}

// IsNotExist reports whether err means no config file.
func IsNotExist(err error) bool {
	return errors.Is(err, os.ErrNotExist)
}
